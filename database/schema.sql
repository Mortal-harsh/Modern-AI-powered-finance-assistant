-- Drop existing tables and sequences safely if they exist
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN ('BUDGETS', 'TRANSACTIONS', 'CATEGORIES', 'USERS')) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
    
    FOR s IN (SELECT sequence_name FROM user_sequences WHERE sequence_name IN ('SEQ_USERS', 'SEQ_CATEGORIES', 'SEQ_TRANSACTIONS', 'SEQ_BUDGETS')) LOOP
        EXECUTE IMMEDIATE 'DROP SEQUENCE ' || s.sequence_name;
    END LOOP;
END;
/

-- ============================================================================
-- 1. USERS TABLE & SEQUENCE
-- ============================================================================
CREATE SEQUENCE SEQ_USERS START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE USERS (
    USER_ID     NUMBER PRIMARY KEY,
    USERNAME    VARCHAR2(50) NOT NULL UNIQUE,
    FULL_NAME   VARCHAR2(100) NOT NULL,
    EMAIL       VARCHAR2(100),
    CREATED_AT  DATE DEFAULT SYSDATE NOT NULL
);

CREATE OR REPLACE TRIGGER TRG_USERS_BI
BEFORE INSERT ON USERS
FOR EACH ROW
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        SELECT SEQ_USERS.NEXTVAL INTO :NEW.USER_ID FROM DUAL;
    END IF;
END;
/

-- ============================================================================
-- 2. CATEGORIES TABLE & SEQUENCE
-- ============================================================================
CREATE SEQUENCE SEQ_CATEGORIES START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE CATEGORIES (
    CATEGORY_ID   NUMBER PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(50) NOT NULL UNIQUE,
    CATEGORY_TYPE VARCHAR2(20) NOT NULL,
    DESCRIPTION   VARCHAR2(255),
    IS_ACTIVE     CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT CHK_CAT_TYPE CHECK (CATEGORY_TYPE IN ('EXPENSE', 'INCOME', 'BOTH')),
    CONSTRAINT CHK_CAT_ACTIVE CHECK (IS_ACTIVE IN ('Y', 'N'))
);

CREATE OR REPLACE TRIGGER TRG_CATEGORIES_BI
BEFORE INSERT ON CATEGORIES
FOR EACH ROW
BEGIN
    IF :NEW.CATEGORY_ID IS NULL THEN
        SELECT SEQ_CATEGORIES.NEXTVAL INTO :NEW.CATEGORY_ID FROM DUAL;
    END IF;
END;
/

-- ============================================================================
-- 3. TRANSACTIONS TABLE & SEQUENCE
-- ============================================================================
CREATE SEQUENCE SEQ_TRANSACTIONS START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID    NUMBER PRIMARY KEY,
    USER_ID           NUMBER NOT NULL,
    CATEGORY_ID       NUMBER NOT NULL,
    TRANSACTION_TYPE  VARCHAR2(20) NOT NULL,
    EXPENSE_TYPE      VARCHAR2(30) DEFAULT 'NEED' NOT NULL,
    AMOUNT            NUMBER(14, 2) NOT NULL,
    TRANSACTION_DATE  DATE NOT NULL,
    PAYMENT_METHOD    VARCHAR2(50) DEFAULT 'UPI' NOT NULL,
    DESCRIPTION       VARCHAR2(255) NOT NULL,
    NOTES             VARCHAR2(1000),
    CREATED_AT        DATE DEFAULT SYSDATE NOT NULL,
    UPDATED_AT        DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_TX_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_TX_CAT FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID),
    CONSTRAINT CHK_TX_TYPE CHECK (TRANSACTION_TYPE IN ('INCOME', 'EXPENSE')),
    CONSTRAINT CHK_TX_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CHK_TX_EXP_TYPE CHECK (EXPENSE_TYPE IN ('NEED', 'WANTS', 'SELF', 'ANONYMOUS', 'INVESTMENT', 'SAVINGS', 'OTHER'))
);

CREATE OR REPLACE TRIGGER TRG_TRANSACTIONS_BI
BEFORE INSERT ON TRANSACTIONS
FOR EACH ROW
BEGIN
    IF :NEW.TRANSACTION_ID IS NULL THEN
        SELECT SEQ_TRANSACTIONS.NEXTVAL INTO :NEW.TRANSACTION_ID FROM DUAL;
    END IF;
    :NEW.CREATED_AT := NVL(:NEW.CREATED_AT, SYSDATE);
    :NEW.UPDATED_AT := SYSDATE;
END;
/

CREATE OR REPLACE TRIGGER TRG_TRANSACTIONS_BU
BEFORE UPDATE ON TRANSACTIONS
FOR EACH ROW
BEGIN
    :NEW.UPDATED_AT := SYSDATE;
END;
/

-- Indexes for fast filtering and reporting
CREATE INDEX IDX_TX_USER_DATE ON TRANSACTIONS(USER_ID, TRANSACTION_DATE);
CREATE INDEX IDX_TX_CATEGORY ON TRANSACTIONS(CATEGORY_ID);
CREATE INDEX IDX_TX_TYPE ON TRANSACTIONS(TRANSACTION_TYPE);

-- ============================================================================
-- 4. BUDGETS TABLE & SEQUENCE
-- ============================================================================
CREATE SEQUENCE SEQ_BUDGETS START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE BUDGETS (
    BUDGET_ID        NUMBER PRIMARY KEY,
    USER_ID          NUMBER NOT NULL,
    CATEGORY_ID      NUMBER, -- NULL indicates Overall Monthly Budget
    BUDGET_MONTH     NUMBER(2) NOT NULL,
    BUDGET_YEAR      NUMBER(4) NOT NULL,
    BUDGET_AMOUNT    NUMBER(14, 2) NOT NULL,
    ALERT_THRESHOLD  NUMBER(3) DEFAULT 80 NOT NULL,
    CREATED_AT       DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT FK_BUDGET_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_BUDGET_CAT FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE CASCADE,
    CONSTRAINT CHK_BUDGET_MONTH CHECK (BUDGET_MONTH BETWEEN 1 AND 12),
    CONSTRAINT CHK_BUDGET_YEAR CHECK (BUDGET_YEAR >= 2000),
    CONSTRAINT CHK_BUDGET_AMOUNT CHECK (BUDGET_AMOUNT > 0),
    CONSTRAINT CHK_ALERT_THRESHOLD CHECK (ALERT_THRESHOLD BETWEEN 1 AND 100)
);

-- Unique index preventing duplicate budgets for same user, year, month, and scope (overall vs category)
CREATE UNIQUE INDEX UIX_BUDGET_SCOPE ON BUDGETS(USER_ID, BUDGET_YEAR, BUDGET_MONTH, NVL(CATEGORY_ID, 0));

CREATE OR REPLACE TRIGGER TRG_BUDGETS_BI
BEFORE INSERT ON BUDGETS
FOR EACH ROW
BEGIN
    IF :NEW.BUDGET_ID IS NULL THEN
        SELECT SEQ_BUDGETS.NEXTVAL INTO :NEW.BUDGET_ID FROM DUAL;
    END IF;
    :NEW.CREATED_AT := NVL(:NEW.CREATED_AT, SYSDATE);
END;
/
